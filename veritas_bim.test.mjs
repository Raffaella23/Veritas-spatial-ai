// Una scatola 10 x 8 x 3 chiusa, facce in ordine antiorario viste da sopra.
function scatola(lx, ly, lz, ox = 0, oy = 0, oz = 0) {
  const v = [], idx = [];
  const p = [
    [0, 0, 0], [lx, 0, 0], [lx, 0, lz], [0, 0, lz],
    [0, ly, 0], [lx, ly, 0], [lx, ly, lz], [0, ly, lz],
  ].map((q) => [q[0] + ox, q[1] + oy, q[2] + oz]);
  for (const q of p) v.push(q[0], q[1], q[2], 0, 1, 0);
  const facce = [
    [0, 1, 2], [0, 2, 3],   // sotto
    [4, 6, 5], [4, 7, 6],   // sopra
    [0, 4, 5], [0, 5, 1], [1, 5, 6], [1, 6, 2],
    [2, 6, 7], [2, 7, 3], [3, 7, 4], [3, 4, 0],
  ];
  for (const f of facce) idx.push(...f);
  return { v: new Float32Array(v), idx: new Uint32Array(idx) };
}
const s = scatola(10, 3, 8);
const m = misuraVolume(s.v, s.idx, null);
vicino(m.areaM2, 80, 0.01, "una stanza 10 x 8 misura 80 m2 di pavimento");
vicino(m.centro[0], 5, 0.01, "il baricentro in X");
vicino(m.centro[2], 4, 0.01, "il baricentro in Z");
vicino(m.centro[1], 0, 0.01, "la quota e' il PAVIMENTO, non il centro del volume");
vicino(m.ingombro.max[1] - m.ingombro.min[1], 3, 0.01, "l'altezza della stanza");

// La stessa scatola con le facce girate al contrario: e' il difetto che il
// 18/08 sera aveva dato zero poligoni su ogni scena di prova.
