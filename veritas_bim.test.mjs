let WebIFC = null;
try { WebIFC = await import("web-ifc"); }
catch (e) { WebIFC = null; }

const percorso = new URL("./banco/finti/casa_finta.ifc", import.meta.url);
if (!WebIFC) {
  saltate++;
  console.log("  SALTATE — web-ifc non installato (npm install web-ifc@0.0.77)");
} else if (!fs.existsSync(percorso)) {
  saltate++;
  console.log("  SALTATE — manca banco/finti/casa_finta.ifc");
} else {
  const dati = new Uint8Array(fs.readFileSync(percorso));
  ok(eIfc(dati), "il file di prova si riconosce dai byte");

  const esito = await leggi(dati, { webifc: WebIFC, wasm: null, conGeometria: false });

  uguale(esito.schema, "IFC4", "schema letto");
  uguale(esito.conteggi.spazi, 4, "quattro ambienti dichiarati");
  uguale(esito.conteggi.conNome, 3, "tre hanno un nome, uno solo un numero");

  const perNome = new Map(esito.spazi.map((x) => [x.nome, x]));
  ok(perNome.has("Sala d'attesa"), "il nome viene da LongName, non da Name — sul lettore VERO");
  uguale(perNome.get("Sala d'attesa").numero, "101", "e il numero della stanza e' 101");
  ok(esito.spazi.some((x) => x.nome === null && x.numero === "103"),
    "la stanza senza LongName non ha ricevuto un nome inventato");

  // le misure, dai volumi dichiarati nel file: 10x8 = 80, 12x8 = 96, 4x4 = 16
  vicino(perNome.get("Sala d'attesa").areaM2, 80, 0.5, "80 m2 misurati dal volume dichiarato");
  vicino(perNome.get("Gate A").areaM2, 96, 0.5, "96 m2 per il secondo ambiente");
  vicino(perNome.get("Sala d'attesa").centro[0], 5, 0.2, "il baricentro sta dove il file lo mette");

  uguale(esito.conteggi.piani, 1, "un piano");
  uguale(esito.spazi[0].piano, "Piano terra",
    "il nome del piano viene da Name, e l'identificativo interno in LongName viene buttato");

  // il muro c'e', e non deve collegare niente
  uguale(esito.collegamenti.length, 1,
    "un solo collegamento: la porta interna. Il muro borda due stanze e non le collega");
  uguale(esito.collegamenti[0].tipo, "porta", "ed e' una porta");
  uguale(esito.esterni.length, 1, "una porta da' sull'esterno");
  const ingresso = esito.spazi.find((x) => x.id === esito.esterni[0].spazio);
  uguale(ingresso.nome, "Sala d'attesa", "e dichiara da dove si entra");

  // il bordo che punta a un elemento inesistente non fa cadere la lettura
  ok(esito.avvisi.some((a) => /non c'e'/.test(a)),
    "il bordo rotto viene dichiarato invece di far cadere il file");

  // l'affollamento, dichiarato dal progettista
  uguale(esito.dati.affollamento, 160, "l'affollamento dichiarato: 120 + 40");
  uguale(esito.dati.daSpazi, 2, "su due ambienti");

  // le zone che escono. Il «Locale tecnico» nel file e' dichiarato SENZA
  // volume: esiste e ha un nome, ma nessuno ha detto dove sta. Non diventa una
  // tappa, e la cosa viene detta invece che taciuta.
  const perEtichetta = new Map(esito.zone.map((z) => [z.label, z]));
  uguale(esito.zone.length, 3, "tre zone: l'ambiente senza volume non ne diventa una");
  ok(!perEtichetta.has("Locale tecnico"),
    "l'ambiente senza volume resta fuori dalle tappe");
  ok(esito.spazi.some((x) => x.nome === "Locale tecnico"),
    "ma resta negli ambienti letti, perche' il file lo dichiara");
  ok(esito.avvisi.some((a) => /senza un volume/.test(a)),
    "e il motivo si legge negli avvisi, non si indovina");
  uguale(perEtichetta.get("Sala d'attesa").type, "spawn",
    "chi ha la porta verso l'esterno e' l'ingresso, comunque si chiami");
  uguale(perEtichetta.get("Gate A").type, "gate", "il gate viene dal nome dichiarato");
  ok(esito.zone.every((z) => z.origine === "bim"), "tutte dichiarano di venire dal BIM");

  // le isole: la stanza 103 e la 104 non comunicano con nessuno
  ok(esito.isole.length > 1, "gli ambienti scollegati sono dichiarati, non usati in silenzio");

  const testo = riassunto(esito);
  ok(/4 ambienti dichiarati/.test(testo), "il racconto dice quanti ambienti ha letto");
  ok(/non li ho dedotti/.test(testo), "e dichiara che i nomi non sono dedotti");

  console.log("\n  --- quello che il file dice, in chiaro ---");
  console.log("  " + testo);
  for (const z of esito.zone) {
    console.log("   ", z.label.padEnd(22), z.type.padEnd(9),
      (z.areaM2 ? z.areaM2.toFixed(1) + " m2" : "—").padStart(9),
      z.confermata ? "confermata" : "DA CONFERMARE");
  }
  for (const a of esito.avvisi) console.log("    avviso:", a);
}

